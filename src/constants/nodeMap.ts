/** 根据经纬度判断所属大洲 */
export function getContinentByCoords(lng: number, lat: number): string {
  if (lng >= -170 && lng <= -30 && lat >= 15 && lat <= 75) return "北美洲";
  if (lng >= -85 && lng <= -35 && lat >= -55 && lat <= 15) return "南美洲";
  if (lng >= -25 && lng <= 60 && lat >= 35 && lat <= 75) return "欧洲";
  if (lng >= -20 && lng <= 55 && lat >= -35 && lat <= 35) return "非洲";
  if (lng >= 25 && lng <= 180 && lat >= -10 && lat <= 75) return "亚洲";
  if (lng >= 110 && lng <= 180 && lat >= -50 && lat <= -10) return "大洋洲";
  return "其他";
}

